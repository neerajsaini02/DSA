// H1 Calculator

#include<iostream>
using namespace std;

int main(){
    int N;
    int M;
    cin>>N;
    cin>>M;
    cout<<N<<" + "<<M<<" = "<<N+M<<endl;
    cout<<N<<" - "<<M<<" = "<<N-M<<endl;
    cout<<N<<" * "<<M<<" = "<<N*M<<endl;
    cout<<N<<" / "<<M<<" = "<<N/M<<endl;
    cout<<N<<" % "<<M<<" = "<<N%M<<endl;
}